# =====================================
# 1. \n - New Line
# =====================================

print("Hello\nWorld")

# Output:
# Hello
# World


# =====================================
# 2. \t - Horizontal Tab
# =====================================

print("Hello\tWorld")

# Output:
# Hello   World


# =====================================
# 3. \\ - Print Backslash
# =====================================

print("C:\\Users\\Dell\\Python")

# Output:
# C:\Users\Dell\Python


# =====================================
# 4. \' - Single Quote
# =====================================

print('It\'s Python')

# Output:
# It's Python


# =====================================
# 5. \" - Double Quote
# =====================================

print("He said, \"Hello\"")

# Output:
# He said, "Hello"


a = "Akash is a good bot \n not a bad boy"

print(a)
