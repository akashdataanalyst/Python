# 5. Write a program to count the number of zeros in the following tuple:
# a = (7, 0, 8, 0, 0, 9)

# Creating a tuple
a = (7, 0, 8, 0, 0, 9)

# Counting how many times 0 appears in the tuple
print(a.count(0))

# Output:
# 3

# Conclusion:
# count() method returns the number of times
# a specified element appears in a tuple.